/**
 * `compaction/summary-prompt.ts` —— 摘要请求的提示词（Phase 3；spec P3 §3）。
 *
 * 【为什么要单独一个文件】这些字符串是**会被反复打磨的资产**（摘要质量直接影响压缩之后
 * 的每一轮），而它们的形状（分节、标签、语气）与压缩算法无关。放在 `summarize.ts` 里会
 * 让"改一句话"和"改切点算法"混在一次 diff 里。
 *
 * 【分节格式为什么是固定英文标题】摘要是给**下一个模型**读的结构化检查点，不是给人读的
 * 文章。固定的 `## Goal` / `## Progress` 让"摘要里有没有下一步"这种问题可以被程序断言，
 * 也让不同轮次生成的摘要在形状上一致（模型更容易忽略"上一份摘要的格式漂了"）。
 *
 * 【`<read-files>` / `<modified-files>` 为什么是标签而不是正文】它们是**累积**的元数据
 * （下一次压缩要接着数），标签让 `summarize.ts` 在拼接与解析之间不需要额外的分隔约定。
 */

/** 摘要请求的 system。**不要继续对话**这条是必须的：否则模型会顺便开始答题。 */
export const SUMMARIZATION_SYSTEM_PROMPT = `你是一个上下文摘要助手。你的任务是阅读一段用户与 AI 助手的对话，然后严格按指定格式产出一份结构化摘要。

不要继续这段对话，不要回答对话里的任何问题，只输出结构化摘要。`;

/** 首次摘要（对话里还没有摘要）。 */
