/**
 * split turn 的"前半段摘要"。
 *
 * 【为什么它和普通摘要不是同一份提示词】普通摘要要覆盖"目标 + 全部进展"；turn prefix 的
 * 读者已经拿着后缀（最近的工作）与历史摘要，它唯一要回答的是"这半段里有什么是看懂后缀
 * 所必需的"。用普通模板会让两份摘要互相重复，也更容易丢掉"用户到底要什么"这一句。
 */
export const TURN_PREFIX_SUMMARIZATION_PROMPT = `这是**被切开的一轮**的前半段（PREFIX）。这一轮的后半段（suffix，也就是最近的工作）已经被保留下来了。

把这半段总结清楚，给保留下来的后缀提供上下文：

## Original Request
[用户在这一轮里要的是什么？]

## Early Progress
- [前半段里的关键决定与已完成的工作]

## Context for Suffix
- [理解保留下来的那部分工作所需要的信息]

简短一点，只保留看懂后缀需要的东西。`;
